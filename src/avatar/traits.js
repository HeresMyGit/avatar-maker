const baseEyes = new Set(['eyes_normal', 'eyes_metal', 'eyes_mfercoin', 'eyes_alien', 'eyes_red', 'eyes_zombie', 'eyes_robot']);

export function resolveTraitMeshes(selectedTraits = {}) {
  const names = new Set();
  const body = selectedTraits.type;
  const defaultEye = { metal: 'eyes_metal', based: 'eyes_mfercoin', zombie: 'eyes_zombie', alien: 'eyes_alien', robot: 'eyes_robot' }[body] || 'eyes_normal';
  for (const [category, value] of Object.entries(selectedTraits)) {
    let meshes = TRAIT_MESH_MAPPING[category]?.[value];
    if (!meshes) continue;
    if (category === 'mouth') {
      meshes = value === 'robot' ? ['mouth_robot'] : meshes.map(name =>
        body === 'metal' ? `${name}_metal` : body === 'based' ? `${name}_mfercoin` : name);
    }
    if (category === 'eyes') {
      const requested = `eyes_${value}`;
      const accessories = meshes.filter(name => !baseEyes.has(name));
      const accessoryEye = body === 'robot' && accessories.length ? 'eyes_normal' : defaultEye;
      meshes = [baseEyes.has(requested) ? requested : accessoryEye, ...accessories];
    }
    meshes.forEach(name => names.add(name));
  }
  return names;
}

export function applyTraitVisibility(avatar, selectedTraits) {
  const names = resolveTraitMeshes(selectedTraits);
  avatar.traverse(object => {
    if (!object.isMesh || object.name === 'tongue' || object.userData.mferAttachmentReference) return;
    object.visible = names.has(object.name);
  });
  return names;
}
